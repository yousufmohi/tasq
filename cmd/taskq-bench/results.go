// summarizeFailure prints Markdown tables for a directory written by
// bench/failure.sh: runs.tsv plus run<N>/<test>.json reports
// (internal/verify.Report). Every number is copied from those files; the
// only arithmetic is min/median/max across runs and sums.
func summarizeFailure(dir string) error {
	runs, err := readRuns(filepath.Join(dir, "runs.tsv"))
	if err != nil {
		return err
	}
	type report struct {
		zeroLoss bool
		fields   map[string]float64
	}
	// data[test][run] = report
	data := map[string]map[int]report{}
	var fieldOrder []string
	seenField := map[string]bool{}
	addField := func(f string) {
		if !seenField[f] {
			seenField[f] = true
			fieldOrder = append(fieldOrder, f)
		}
	}
	for _, r := range runs {
		files, _ := filepath.Glob(filepath.Join(dir, fmt.Sprintf("run%d", r.n), "*.json"))
		for _, f := range files {
			b, err := os.ReadFile(f)
			if err != nil {
				return err
			}
			var m map[string]any
			if err := json.Unmarshal(b, &m); err != nil {
				return fmt.Errorf("%s: %w", f, err)
			}
			test, _ := m["test"].(string)
			rep := report{fields: map[string]float64{}}
			rep.zeroLoss, _ = m["zero_loss_asserted"].(bool)
			keys := make([]string, 0, len(m))
			for k := range m {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			for _, k := range reportFieldOrder(keys) {
				if v, ok := m[k].(float64); ok {
					rep.fields[k] = v
					addField(k)
				}
			}
			if extra, ok := m["extra"].(map[string]any); ok {
				ek := make([]string, 0, len(extra))
				for k := range extra {
					ek = append(ek, k)
				}
				sort.Strings(ek)
				for _, k := range ek {
					if v, ok := extra[k].(float64); ok {
						rep.fields["extra."+k] = v
						addField("extra." + k)
					}
				}
			}
			if data[test] == nil {
				data[test] = map[int]report{}
			}
			data[test][r.n] = rep
		}
	}
	tests := make([]string, 0, len(data))
	for t := range data {
		tests = append(tests, t)
	}
	sort.Strings(tests)

	fmt.Printf("# Failure suite: %d runs\n\n", len(runs))
	fmt.Println("Generated by `taskq-bench -mode summarize-failure` from `runs.tsv` and `run<N>/*.json`.")
	fmt.Println("Field meanings: `internal/verify/verify.go` (Report). A `-` means the run produced no report for that scenario.")
	fmt.Println()
	fmt.Println("## Runs")
	fmt.Println("| run | go test exit code | seconds | failed tests |")
	fmt.Println("|---|---|---|---|")
	for _, r := range runs {
		fmt.Printf("| %d | %d | %d | %s |\n", r.n, r.exit, r.seconds, r.failed)
	}

	fmt.Println("\n## Scenarios that assert zero loss")
	fmt.Println("Sum over every report with `zero_loss_asserted: true` (demonstrations and positive controls excluded).")
	fmt.Println()
	fmt.Println("| run | scenarios | acked | lost | duplicate executions | duplicate naive effects | duplicate idem.Once effects |")
	fmt.Println("|---|---|---|---|---|---|---|")
	var tot [6]float64
	for _, r := range runs {
		var n, acked, lost, dx, de, do float64
		for _, t := range tests {
			rep, ok := data[t][r.n]
			if !ok || !rep.zeroLoss {
				continue
			}
			n++
			acked += rep.fields["acked"]
			lost += rep.fields["lost"]
			dx += rep.fields["duplicate_executions"]
			de += rep.fields["duplicate_effects"]
			do += rep.fields["duplicate_once_effects"]
		}
		fmt.Printf("| %d | %.0f | %.0f | %.0f | %.0f | %.0f | %.0f |\n", r.n, n, acked, lost, dx, de, do)
		for i, v := range []float64{n, acked, lost, dx, de, do} {
			tot[i] += v
		}
	}
	fmt.Printf("| **all** | %.0f | %.0f | %.0f | %.0f | %.0f | %.0f |\n", tot[0], tot[1], tot[2], tot[3], tot[4], tot[5])

	fmt.Println("\n## Per scenario")
	for _, t := range tests {
		zl := false
		for _, rep := range data[t] {
			zl = zl || rep.zeroLoss
		}
		fmt.Printf("\n### %s\n", t)
		if zl {
			fmt.Println("Asserts zero loss.")
		} else {
			fmt.Println("Reports loss without asserting zero (demonstration or positive control).")
		}
		fmt.Println()
		hdr := "| field |"
		sep := "|---|"
		for _, r := range runs {
			hdr += fmt.Sprintf(" run %d |", r.n)
			sep += "---|"
		}
		fmt.Println(hdr + " min | median | max |")
		fmt.Println(sep + "---|---|---|")
		for _, f := range fieldOrder {
			var vals []float64
			row := "| " + f + " |"
			present := false
			for _, r := range runs {
				rep, ok := data[t][r.n]
				v, has := rep.fields[f]
				if !ok || !has {
					row += " - |"
					continue
				}
				present = true
				vals = append(vals, v)
				row += " " + num(v) + " |"
			}
			if !present {
				continue
			}
			slices.Sort(vals)
			row += fmt.Sprintf(" %s | %s | %s |", num(vals[0]), num(median(vals)), num(vals[len(vals)-1]))
			fmt.Println(row)
		}
	}
	return nil
}

// reportFieldOrder puts the headline fields first.
func reportFieldOrder(keys []string) []string {
	first := []string{"acked", "lost", "succeeded", "dead", "forgotten_after_success",
		"executions", "duplicate_executions", "effects", "duplicate_effects",
		"once_effects", "duplicate_once_effects", "applied", "applied_not_acked",
		"reclaimed", "succeeded_without_execution"}
	out := []string{}
	for _, k := range first {
		if slices.Contains(keys, k) {
			out = append(out, k)
		}
	}
	for _, k := range keys {
		if !slices.Contains(first, k) {
			out = append(out, k)
		}
	}
	return out
}

func num(v float64) string {
	if v == math.Trunc(v) {
		return strconv.FormatFloat(v, 'f', 0, 64)
	}
	return strconv.FormatFloat(v, 'f', 3, 64)
}

type run struct {
	n, exit, seconds int
	failed           string
}

func readRuns(path string) ([]run, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var runs []run
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fs := strings.Split(sc.Text(), "\t")
		if len(fs) < 4 || fs[0] == "run" {
			continue
		}
		n, _ := strconv.Atoi(fs[0])
		e, _ := strconv.Atoi(fs[1])
		s, _ := strconv.Atoi(fs[2])
		runs = append(runs, run{n: n, exit: e, seconds: s, failed: fs[3]})
	}
	return runs, sc.Err()
}

// summarizeTests prints pass/fail/skip counts per test from the
// `go test -json` logs (run<N>.json.gz) written by bench/integration.sh.
func summarizeTests(dir string) error {
	runs, err := readRuns(filepath.Join(dir, "runs.tsv"))
	if err != nil {
		return err
	}
	type count struct{ pass, fail, skip int }
	counts := map[string]*count{} // "pkg TestName"
	for _, r := range runs {
		f, err := os.Open(filepath.Join(dir, fmt.Sprintf("run%d.json.gz", r.n)))
		if err != nil {
			return err
		}
		gz, err := gzip.NewReader(f)
		if err != nil {
			f.Close()
			return err
		}
		dec := json.NewDecoder(gz)
		for {
			var ev struct {
				Action, Package, Test string
			}
			if err := dec.Decode(&ev); err == io.EOF {
				break
			} else if err != nil {
				// go test -json interleaves non-JSON build output on failure.
				break
			}
			if ev.Test == "" {
				continue
			}
			k := shortPkg(ev.Package) + " " + ev.Test
			c := counts[k]
			if c == nil {
				c = &count{}
				counts[k] = c
			}
			switch ev.Action {
			case "pass":
				c.pass++
			case "fail":
				c.fail++
			case "skip":
				c.skip++
			}
		}
		gz.Close()
		f.Close()
	}
	names := make([]string, 0, len(counts))
	for k := range counts {
		names = append(names, k)
	}
	sort.Strings(names)
	var tp, tf, ts int
	for _, k := range names {
		tp += counts[k].pass
		tf += counts[k].fail
		ts += counts[k].skip
	}
	fmt.Printf("# Test suite: %d runs\n\n", len(runs))
	fmt.Println("Generated by `taskq-bench -mode summarize-tests` from the `go test -json` logs (`run<N>.json.gz`).")
	fmt.Println()
	fmt.Println("| run | go test exit code | seconds | failed tests |")
	fmt.Println("|---|---|---|---|")
	for _, r := range runs {
		fmt.Printf("| %d | %d | %d | %s |\n", r.n, r.exit, r.seconds, r.failed)
	}
	fmt.Printf("\nTest results summed over runs (subtests counted separately): %d passed, %d failed, %d skipped.\n\n", tp, tf, ts)
	fmt.Println("| package | test | passed | failed | skipped |")
	fmt.Println("|---|---|---|---|---|")
	for _, k := range names {
		pkg, test, _ := strings.Cut(k, " ")
		c := counts[k]
		fmt.Printf("| %s | %s | %d | %d | %d |\n", pkg, test, c.pass, c.fail, c.skip)
	}
	return nil
}

var modPrefix = regexp.MustCompile(`^github\.com/[^/]+/[^/]+/?`)

func shortPkg(p string) string {
	s := modPrefix.ReplaceAllString(p, "")
	if s == "" {
		return "(root)"
	}
	return s
}
